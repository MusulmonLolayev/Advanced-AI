"""Write narration/labels.md: one list of every on-screen label, for all lectures.

Every label is a w(en, uz) call in a lectureNN_*.py file. Each Uzbek/English pair is listed
once, under the lecture that first shows it, with every place it appears; a label approved
once stays approved in later lectures. Pairs whose Uzbek or English side is translated two
ways are listed first, so a term reads the same in every video.

    uv run python labels.py
"""
import ast
import re
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE / "narration" / "labels.md"
FILE = re.compile(r"lecture(\d\d)_(kit|s(\d\d))\.py$")


def text(node):
    """A label's text: a literal as written, an f-string with {expr} placeholders."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return "".join(v.value if isinstance(v, ast.Constant) else "{" + ast.unparse(v.value) + "}"
                       for v in node.values)
    return None


def where(path):
    m = FILE.search(path.name)
    lec = int(m[1])
    if m[2] == "kit":
        return lec, -1, f"L{lec} (all)"
    sec = int(m[3])
    return lec, sec, f"L{lec} opening" if sec == 0 else f"L{lec} §{sec}"


def collect():
    """{(uz, en): [(lecture, section, place)]} in lecture and section order."""
    seen = defaultdict(list)
    files = sorted((p for p in HERE.glob("lecture*.py") if FILE.search(p.name)), key=lambda p: where(p)[:2])
    for path in files:
        place = where(path)
        for node in ast.walk(ast.parse(path.read_text())):
            if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "w" and len(node.args) == 2:
                en, uz = map(text, node.args)
                if en is not None and uz is not None and place not in seen[(uz, en)]:
                    seen[(uz, en)].append(place)
    return seen


def cell(s):
    return s.replace("|", "\\|").replace("\n", "<br>")


def places(ps):
    """'L1 §1, §3; L2 §4' from [(lecture, section, place)]."""
    out, last = [], None
    for lec, _, p in ps:
        out.append(p if lec != last else p.split(" ", 1)[1])
        last = lec
    return re.sub(r", (L\d)", r"; \1", ", ".join(out))


def main():
    seen = collect()
    by_uz, by_en = defaultdict(set), defaultdict(set)
    for uz, en in seen:
        by_uz[uz].add(en), by_en[en].add(uz)
    clash = sorted({(uz, en) for uz, en in seen if len(by_uz[uz]) > 1 or len(by_en[en]) > 1},
                   key=lambda k: (k[1].lower(), k[0]))

    md = ["# On-screen labels — all lectures (for approval)", "",
          "Every label the videos show, in Uzbek with its English counterpart. Each pair is listed once, under the",
          "lecture that first shows it; *Shown in* lists every place it appears, so a label approved here stays",
          "approved in later lectures. `{…}` is filled in from that lecture's captured numbers. Narration lines are",
          "approved separately in `lectureNN.md`. Generated by `labels.py` from the `w(en, uz)` calls — edit the",
          "scenes, not this file. Send corrections as Uzbek label → fix.", ""]
    if clash:
        md += ["## Translated two ways — pick one", "",
               "The same Uzbek or English text has more than one counterpart below.", "",
               "| Uzbek | English | Shown in |", "|---|---|---|"]
        md += [f"| {cell(uz)} | {cell(en)} | {places(seen[(uz, en)])} |" for uz, en in clash]
        md.append("")
    for lec in sorted({ps[0][0] for ps in seen.values()}):
        rows = [(k, ps) for k, ps in seen.items() if ps[0][0] == lec]
        md += [f"## Lecture {lec}" + (" — new labels" if lec > 1 else ""), "",
               f"{len(rows)} labels.", "", "| Uzbek | English | Shown in |", "|---|---|---|"]
        md += [f"| {cell(uz)} | {cell(en)} | {places(ps)} |" for (uz, en), ps in rows]
        md.append("")
    OUT.write_text("\n".join(md))
    print(f"{OUT.relative_to(HERE)}: {len(seen)} labels, {len(clash)} translated two ways")


if __name__ == "__main__":
    main()
