"""The model, behind one function: complete(messages, stop) -> the text it writes.

GIVEN: you do not edit this file. Three modes, so a check never depends on the network:
  live     call an OpenAI-compatible API; needs LLM_API_KEY (and optionally LLM_MODEL, LLM_BASE_URL) in .env
  record   live, and save every reply to traces/<name>.json
  replay   play the saved replies back in order, checking that each prompt is the one that was recorded
"""
import hashlib
import json
import os

from uz_agent import config


def fingerprint(messages, stop):
    """A short hash of exactly what the model is asked. A replay compares it, so a loop that builds the messages
    differently from the recorded one is caught on the first call that differs."""
    return hashlib.sha256(json.dumps([messages, stop], ensure_ascii=False).encode()).hexdigest()[:16]


class Model:
    def __init__(self, mode="live", name=None):
        self.mode, self.name, self.calls = mode, name, []
        if mode == "replay":
            self.saved = json.loads((config.TRACES / f"{name}.json").read_text())["calls"]
        else:
            if not os.environ.get("LLM_API_KEY"):
                raise SystemExit("no LLM_API_KEY: put it in .env (see .env.example), or replay a recorded run")
            from openai import OpenAI
            self.client = OpenAI(base_url=config.BASE_URL, api_key=os.environ["LLM_API_KEY"])

    def complete(self, messages, stop=None):
        fp = fingerprint(messages, stop)
        if self.mode == "replay":
            n = len(self.calls)
            if n >= len(self.saved) or self.saved[n]["prompt"] != fp:
                raise RuntimeError(f"replay {self.name}: call {n + 1} differs from the recording -- "
                                   "your loop sent the model something else than the recorded run did")
            text = self.saved[n]["reply"]
        else:
            r = self.client.chat.completions.create(model=config.MODEL, messages=messages, stop=stop,
                                                    temperature=config.TEMPERATURE)
            text = r.choices[0].message.content or ""
        self.calls.append({"prompt": fp, "reply": text})
        return text

    def save(self, extra):
        if self.mode == "record":
            path = config.TRACES / f"{self.name}.json"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps({"model": config.MODEL, **extra, "calls": self.calls},
                                       ensure_ascii=False, indent=1))
